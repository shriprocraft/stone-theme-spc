/** Serialise JSON-LD so it can never terminate its own <script> element:
 *  "<" is escaped (covers "</script>" and "<!--"), as are the two line
 *  separators that are valid JSON but not valid in older JS engines. */
function safeJson(data: object): string {
  return JSON.stringify(data)
    .replace(/</g, "\\u003c")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
}

export function JsonLd({ data }: { data: object | null }) {
  if (!data) return null;
  return (
    <script
      type="application/ld+json"
      // eslint-disable-next-line react/no-danger
      dangerouslySetInnerHTML={{ __html: safeJson(data) }}
    />
  );
}
